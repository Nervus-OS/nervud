// Package audit 是 nervud 的安全审计：谁在什么时候被允许或拒绝了什么。
//
// # 两种实现
//
//	New(log)              只写 slog。测试与最小装配用。
//	NewFileRecorder(cfg)  append-only 哈希链文件 + slog 镜像。生产用。
//
// 后者补的是三件 slog 做不到的事：不被日志级别过滤掉、不被轮转策略覆盖、
// 被改动之后能看出来。
//
// # 依赖方向
//
// 本包【不 import 任何兄弟模块】。依赖箭头永远指向 audit，结构上不可能出现
// import cycle——这是它能被权限、租约、装包、Safety 同时调用的前提。
//
// # 完整性保护的边界
//
// 哈希链让【局部篡改】留下痕迹：删几条、改一条、调顺序，都会让它之后的每一条
// prev 对不上。
//
// 它【不防】有 root 权限的人把整个文件重写一遍并重算全链——那需要外部锚点
// （远程日志、TPM、一次性写入介质）。目标是篡改可见，不是篡改不可能。
//
// 绝大多数情况下审计被改动是误操作、日志清理脚本写错、或者一次没想清楚的
// 「整理一下」，而不是有预谋的攻击。那些情形本包全都能暴露。
//
// # 怎么校验
//
//	nervusctl audit-verify [dir]
//
// 它跨文件校验（轮转后的历史文件与当前文件是同一条链），并说清楚校验覆盖到
// 哪一段——轮转回收掉的那部分谁也验不了，工具会明说而不是假装验过。
