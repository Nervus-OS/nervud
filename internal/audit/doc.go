// Package audit 是 nervud 的安全审计：谁在什么时候被允许或拒绝了什么。
//
// # 两种实现
//
//	New(log)              只写 slog。测试与最小装配用。
//	NewFileRecorder(cfg)  append-only 哈希链文件 + slog 镜像。生产用。
//
// 后者补的是三件 slog 做不到的事：不被日志级别过滤掉、不被轮转策略覆盖、
// 被改动之后能看出来。
//
// # 依赖方向
//
// 本包【不 import 任何兄弟模块】。依赖箭头永远指向 audit，结构上不可能出现
// import cycle——这是它能被权限、租约、装包、Safety 同时调用的前提。
//
// # 完整性保护的边界
//
// 哈希链让【局部篡改】留下痕迹：删几条、改一条、调顺序，都会让它之后的每一条
// prev 对不上。
//
// 它【不防】有 root 权限的人把整个文件重写一遍并重算全链——那需要外部锚点
// （远程日志、TPM、一次性写入介质）。目标是篡改可见，不是篡改不可能。
//
// 绝大多数情况下审计被改动是误操作、日志清理脚本写错、或者一次没想清楚的
// 「整理一下」，而不是有预谋的攻击。那些情形本包全都能暴露。
//
// # 掉电会丢多少
//
// Write 返回不等于落盘：内容躺在内核页缓存里，Linux 默认最多 30 秒才回写。
// 所以本包自己管 fsync，策略是【批量 + 拒绝类优先】：
//
//   - 定时器每 minSyncInterval（1 秒）落一次盘，仅在有未落盘记录时才动设备
//   - Denied 的记录立刻落盘，但两次之间至少隔 1 秒
//   - 轮转前、停机时无条件落盘，不受节流管
//
// 不逐条 fsync 是因为方向会反过来：SD 卡上一次 fsync 是几到几十毫秒，逐条做会
// 让写 goroutine 的排空速度掉到每秒几十条，突发时队列溢出——为了不丢反而丢。
//
// # 丢了怎么看得出来
//
// 掉电丢掉尾部若干条之后，【剩下的链完全自洽】：序号连续、prev 相扣、哈希全对。
// 光有哈希链的话，校验工具会对一个残缺的文件报「通过」——那不是安全，是一个
// 假的确定性。
//
// 所以干净停机会写一条 ActionClosed 收尾。下次启动看到链尾不是它，就补一条
// ActionUncleanShutdown，把「这里可能少了最多 1 秒的记录」写进链里。
//
// 三种异常在链上各有各的名字，不会互相冒充：
//
//	ActionChainStarted     文件是新建的 / 被删了重建 —— 序号从 1 重来
//	ActionUncleanShutdown  掉电或被 KILL —— 链没断，但尾部可能少了记录
//	ActionChainGap         队列满，明确知道丢了多少条
//
// # 怎么校验
//
//	nervusctl audit-verify [dir]
//
// 它跨文件校验（轮转后的历史文件与当前文件是同一条链），并说清楚校验覆盖到
// 哪一段——轮转回收掉的那部分谁也验不了，工具会明说而不是假装验过。同样地，
// 它会列出每一次 UncleanShutdown 的位置：「链完整」不等于「一条没少」。
